// Measures the difficulty ladder shown on the site and rewrites TRAINED.levels.
import { writeFileSync } from 'node:fs';
import { cpus } from 'node:os';
import { Worker } from 'node:worker_threads';
import { DECKS } from '../js/cards.js';
import { DEFAULT_WEIGHTS } from '../js/ai.js';
import { TRAINED } from '../js/trained.js';

const keys = Object.keys(DECKS);
const GAMES = Number(process.env.LADDER || 400);
const workers = Array.from({ length: Math.max(1, cpus().length - 1) }, () => new Worker(new URL('./worker.mjs', import.meta.url)));
const pending = new Map();
let nextId = 0;
for (const w of workers) w.on('message', ({ id, result }) => { pending.get(id)(result); pending.delete(id); });
const run = (job, w) => new Promise(resolve => { const id = nextId++; pending.set(id, resolve); w.postMessage({ id, job }); });

const agent = (level, deck, trained) => ({ level, weights: trained ? TRAINED.weights.specialists[deck] : DEFAULT_WEIGHTS });
const wilson = (wins, n) => {
  const z = 1.96, p = wins / n, d = 1 + z * z / n;
  const c = (p + z * z / (2 * n)) / d, r = z * Math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d;
  return [c - r, c + r].map(v => +v.toFixed(4));
};

async function match(a, b, seedBase) {
  const jobs = [];
  for (let g = 0; g < GAMES; g++) {
    const da = keys[g % 4], db = keys[(g >> 2) % 4], seat = (g >> 4) % 2;
    const A = agent(a.level, da, a.trained), B = agent(b.level, db, b.trained);
    jobs.push({ seat, job: { decks: seat === 0 ? [da, db] : [db, da], agents: seat === 0 ? [A, B] : [B, A], seed: seedBase + g, first: (g >> 5) % 2 } });
  }
  const results = new Array(jobs.length);
  let cursor = 0;
  await Promise.all(workers.map(async w => { while (cursor < jobs.length) { const i = cursor++; results[i] = await run(jobs[i].job, w); } }));
  let points = 0;
  results.forEach((r, i) => { points += r.winner === 2 ? 0.5 : r.winner === jobs[i].seat ? 1 : 0; });
  return { rate: +(points / GAMES).toFixed(4), games: GAMES, ci: wilson(points, GAMES) };
}

const novice = { level: 'novice', trained: false }, adept = { level: 'adept', trained: false }, master = { level: 'master', trained: true };
const levels = [
  { a: 'adept', b: 'novice', ...(await match(adept, novice, 1.1e6)) },
  { a: 'master', b: 'adept', ...(await match(master, adept, 1.2e6)) },
  { a: 'master', b: 'novice', ...(await match(master, novice, 1.3e6)) },
];
const searchOnly = await match(master, { level: 'adept', trained: true }, 1.4e6);
for (const l of levels) console.log(`${l.a} vs ${l.b}: ${(100 * l.rate).toFixed(1)}% [${l.ci.map(v => (100 * v).toFixed(1)).join('–')}]`);
console.log(`master search vs adept search, same trained evaluator: ${(100 * searchOnly.rate).toFixed(1)}%`);

const trained = { ...TRAINED, levels, searchOnly };
writeFileSync(new URL('../js/trained.js', import.meta.url),
  `// Generated by tools/train.mjs and tools/ladder.mjs from self-play games. Do not edit by hand.\nexport const TRAINED = ${JSON.stringify(trained, null, 2)};\n`);
await Promise.all(workers.map(w => w.terminate()));
